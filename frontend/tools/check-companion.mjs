import assert from 'node:assert/strict'

export async function checkCompanion(page, { base, roomId, screenshot, check }) {
  await page.goto(`${base}/quests/${roomId}`, { waitUntil: 'domcontentloaded' })
  await page.getByRole('navigation', { name: 'Workspace tools' }).getByRole('button', { name: 'Companion', exact: true }).click()
  const companion = page.getByRole('complementary', { name: 'Private Companion', exact: true })
  await companion.getByLabel('Ask your Companion', { exact: true }).fill('Help me compare our options.')
  await companion.getByRole('button', { name: 'Ask Companion', exact: true }).click()
  await companion.getByText('Planning suggestion · AI unavailable', { exact: true }).waitFor()
  await page.reload()
  await page.getByRole('navigation', { name: 'Workspace tools' }).getByRole('button', { name: 'Companion', exact: true }).click()
  await companion.getByText('Help me compare our options.', { exact: false }).waitFor()
  assert.equal(await page.locator('.crew-message').filter({ hasText: 'Help me compare our options.' }).count(), 0)
  check('Private Companion conversation survives reload without posting to crew chat')

  await page.goto(`${base}/travel-dna/plan-paths?roomId=${roomId}`, { waitUntil: 'domcontentloaded' })
  await page.locator('.group-option-card').first().click()
  await page.getByRole('button', { name: 'Explain this match', exact: true }).click()
  await page.locator('.itinerary-ai-explanation').getByText('Planning suggestion · AI unavailable', { exact: true }).waitFor()
  await page.locator('.itinerary-companion summary').click()
  await page.getByRole('button', { name: 'Personalise with Companion', exact: true }).click()
  await page.locator('.companion-story').waitFor()
  const title = await page.locator('.companion-story > h3').textContent()
  const originalDays = await page.locator('.group-preview-day').count()
  await page.reload()
  await page.locator('.group-option-card').first().click()
  await page.locator('.itinerary-companion summary').click()
  await page.locator('.companion-story').waitFor()
  assert.equal(await page.locator('.companion-story > h3').textContent(), title)
  assert.equal(await page.locator('.group-preview-day').count(), originalDays)
  check('Explanation and personalised notes persist while preserving the original itinerary')

  await page.goto(`${base}/travel-dna/group-dna?roomId=${roomId}`, { waitUntil: 'domcontentloaded' })
  const extraction = page.getByRole('complementary', { name: 'Preference Companion', exact: true })
  await extraction.getByLabel('Your travel notes', { exact: true }).fill('Food and nature. A relaxed pace. 5 days.')
  await extraction.getByRole('button', { name: 'Shape these notes', exact: true }).click()
  await extraction.getByRole('group', { name: 'Review changes to your preferences' }).waitFor()
  assert.equal(await extraction.getByRole('button', { name: 'Apply selected preferences' }).isDisabled(), true)
  await extraction.getByRole('checkbox', { name: 'Pace Slow & relaxed', exact: true }).check()
  await extraction.getByRole('checkbox', { name: 'Trip length (days) 5', exact: true }).check()
  await extraction.getByRole('button', { name: 'Apply selected preferences' }).click()
  await extraction.getByRole('button', { name: 'Preferences applied', exact: true }).waitFor()
  await screenshot('companion-reviewed-preferences', true)
  await page.reload()
  await extraction.getByRole('button', { name: 'Preferences applied', exact: true }).waitFor()
  assert.equal(await extraction.getByRole('checkbox', { name: 'Pace Slow & relaxed', exact: true }).isChecked(), true)
  assert.equal(await extraction.getByRole('checkbox', { name: 'Travel interests Food & Culture · Nature', exact: true }).isChecked(), false)
  await page.goto(`${base}/travel-dna/preferences?roomId=${roomId}`, { waitUntil: 'domcontentloaded' })
  await page.getByRole('heading', { name: 'The basics.', exact: true }).waitFor()
  assert.equal(await page.getByRole('button', { name: '5 days', exact: true }).getAttribute('aria-pressed'), 'true')
  await page.getByRole('button', { name: 'A little more about you' }).click()
  await page.getByRole('button', { name: 'A little more about you' }).click()
  assert.equal(await page.getByRole('button', { name: 'Slow & relaxed', exact: true }).getAttribute('aria-pressed'), 'true')
  assert.equal(await page.getByRole('button', { name: 'Food & local culture', exact: true }).getAttribute('aria-pressed'), 'true')
  await page.getByRole('button', { name: 'A little more about you' }).click()
  await page.getByRole('button', { name: 'Save my preferences' }).click()
  await page.waitForURL(`**/quests/${roomId}*`)
  check('Extracted preferences require review, apply to the owner, and survive reload')
  await page.goto(`${base}/quests/${roomId}`, { waitUntil: 'domcontentloaded' })
}
