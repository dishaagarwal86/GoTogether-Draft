const open = async account => {
  const context = await browser.newContext({ viewport: { width: 1440, height: 1050 } }); contexts.push(context)
  if (account) await context.addInitScript(value => { localStorage.setItem('gotogether.session-token', value.token); localStorage.setItem('gotogether.current-user-id', value.user.id) }, account)
  const page = await context.newPage(); page.setDefaultTimeout(18000); page.on('pageerror', error => errors.push(error.message)); return page
}
