  await api('/me/travel-style/redemptions', sessions[3].token, redemption)
  const redeemed = await api('/me/travel-style', sessions[3].token)
  assert.equal(redeemed.wallet.points, 0); assert.equal(redeemed.wallet.credits, profile.wallet.credits + 5)
  checks.push('Confirmed travel history and memories; points redeem for five credits exactly once')
