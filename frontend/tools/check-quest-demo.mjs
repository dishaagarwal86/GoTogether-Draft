  const photoCards = page.locator('.canvas-bookings img')
  assert.ok(await photoCards.count() >= 2)
  for (const photo of await photoCards.all()) { await photo.scrollIntoViewIfNeeded(); await photo.evaluate(img => img.decode()) }
  for (const width of [900, 390, 320]) {
    await page.setViewportSize({ width, height: 950 })
    await page.waitForTimeout(500)
    assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth + 1), `No horizontal overflow at ${width}`)
  }
  await page.screenshot({ path: `${out}/agreed-mobile.png`, fullPage: true })
  await page.setViewportSize({ width: 1440, height: 1000 })
  await page.getByLabel('Demo traveller', { exact: true }).selectOption('kabir')
