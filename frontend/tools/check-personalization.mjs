import { chromium } from 'playwright'
import assert from 'node:assert/strict'
import { mkdir, writeFile } from 'node:fs/promises'

const base = process.env.JOURNEY_TEST_URL ?? 'http://127.0.0.1:5186'
assert.equal(new URL(base).hostname, '127.0.0.1')
const out = '.journey-test-results/personalization'
await mkdir(out, { recursive: true })
const browser = await chromium.launch({ channel: 'chrome', headless: true })
const page = await browser.newPage({ viewport: { width: 1440, height: 1100 } })
page.setDefaultTimeout(15000)
const errors = [], checks = []
page.on('pageerror', error => errors.push(error.message))
const check = name => { checks.push(name); console.log('PASS ' + name) }
const shot = async name => {
  await page.evaluate(async () => { window.scrollTo(0, 0); await document.fonts.ready })
  await page.screenshot({ path: `${out}/${name}.png`, fullPage: true, animations: 'disabled' })
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth + 1), false, `${name}: overflow`)
}
let account
const api = async path => (await (await page.request.get(base + '/api' + path, { headers: { Authorization: `Bearer ${account.token}` } })).json()).data
const start = async () => {
  await page.getByLabel('Your trip idea').fill('6 days in Kyoto, food and local culture.')
  await page.getByRole('button', { name: 'Show me a starting point' }).click()
  await page.waitForURL('**/quests/room_*')
  await page.getByRole('region', { name: 'Trip workspace', exact: true }).waitFor()
  return page.url().split('/').at(-1)
}
try {
  await page.goto(base + '/login')
  const response = await page.request.post(base + '/api/auth/signup', { data: { firstName: 'Travel', lastName: 'Memory', email: `personalization-${Date.now()}@example.invalid`, password: 'Synthetic travel 2026!' } })
  assert.equal(response.status(), 201); account = (await response.json()).data
  await page.evaluate(value => { localStorage.setItem('gotogether.session-token', value.token); localStorage.setItem('gotogether.current-user-id', value.user.id) }, account)
  await page.goto(base + '/travel-dna/new')
  const room = await start()
  const editTime = async time => {
    await page.locator('.canvas-activity').first().getByRole('button', { name: 'Edit / replace' }).click()
    await page.getByLabel('Suggested time').fill(time)
    await page.getByRole('button', { name: 'Save this moment', exact: true }).click()
    await page.getByRole('complementary', { name: 'Remember a travel preference' }).waitFor()
  }
  await editTime('11:00')
  await page.getByRole('button', { name: 'Just this trip', exact: true }).click()
  assert.equal((await api('/me/travel-style')).memories.length, 0)
  check('A trip-only edit saves without changing the travel profile')
  await editTime('12:00')
  await shot('01-remember-beside-edit')
  await page.getByRole('button', { name: 'Remember this', exact: true }).click()
  await page.getByText('Remembered for your future plans.', { exact: true }).waitFor()
  await page.getByRole('link', { name: 'See my travel style' }).click()
  await page.getByRole('heading', { name: 'Mornings around 12:00' }).waitFor()
  await page.reload()
  await page.getByRole('heading', { name: 'Mornings around 12:00' }).waitFor()
  await shot('02-travel-style-desktop')
  check('Confirmed memory opens in the private profile and survives reload')
  await page.goto(base + '/travel-dna/new')
  await page.locator('.quick-start-memory').getByText('Mornings around 12:00').waitFor()
  await shot('03-returning-traveller')
  const nextRoom = await start()
  assert.equal((await api(`/working-plans/${nextRoom}`)).days[0].items[0].time, '12:00')
  check('The next matching trip visibly uses the confirmed later start')
  await page.goto(base + `/quests/${room}`)
  await Promise.all([page.waitForResponse(res => res.url().endsWith('/changes') && res.request().method() === 'POST'), page.getByRole('button', { name: 'Undo', exact: true }).click()])
  assert.equal((await api('/me/travel-style')).memories.length, 0)
  check('Undo cancels the source learning without changing other saved trips')
  await page.locator('.canvas-activity').first().getByRole('button', { name: /^Lock / }).click()
  await page.locator('.canvas-activity').first().getByRole('button', { name: /^Unlock / }).waitFor()
  const before = await api(`/working-plans/${room}`)
  await page.getByRole('navigation', { name: 'Workspace tools' }).getByRole('button', { name: 'Companion', exact: true }).click()
  await page.getByRole('button', { name: 'Edit the plan', exact: true }).click()
  await page.getByRole('button', { name: /^Try: move unlocked/ }).click()
  await page.getByRole('button', { name: 'Preview changes · 1 credit' }).click()
  await page.getByRole('button', { name: 'Apply these changes' }).waitFor()
  assert.deepEqual((await api(`/working-plans/${room}`)).days, before.days)
  await shot('04-review-ai-changes')
  await page.setViewportSize({ width: 390, height: 844 })
  await page.getByRole('button', { name: 'Apply these changes' }).scrollIntoViewIfNeeded()
  await shot('04b-mobile-apply-preview')
  await page.getByRole('button', { name: 'Apply these changes' }).click()
  await page.getByText('Applied to your plan. Use Undo to reverse it.', { exact: true }).waitFor()
  const after = await api(`/working-plans/${room}`)
  assert.deepEqual(after.days[0].items[0], before.days[0].items[0])
  assert.notEqual(after.days[0].items[1].time, before.days[0].items[1].time)
  assert.equal((await api('/me/travel-style')).wallet.credits, 3)
  check('Reviewed fallback edits preserve locks, require Apply, and use no credits')
  await page.setViewportSize({ width: 390, height: 844 })
  await shot('05-mobile-companion')
  await page.goto(base + '/travel-style?tab=history')
  await page.getByLabel('Paste a past itinerary').fill('Day 1: Tea houses in the morning and a long lunch, then a pottery workshop.\nDay 2: A quiet garden walk and a cooking class with our friends.')
  await page.getByRole('button', { name: 'Turn this into day cards' }).click()
  await page.getByLabel('Chapter name').fill('Kyoto last spring')
  await page.getByLabel('Destination', { exact: true }).fill('Kyoto')
  await page.getByLabel('Trip ended').fill('2025-04-06')
  await page.getByRole('button', { name: 'Food & Culture', exact: true }).click()
  await page.getByLabel('Your favourite part—or what you’d change').fill('The quiet mornings and cooking class were wonderful. Next time I would stay longer.')
  await page.getByText('Draft saved · return whenever you like', { exact: true }).waitFor()
  await page.reload()
  await page.getByRole('button', { name: 'Continue review' }).click()
  assert.equal(await page.getByLabel('Chapter name').inputValue(), 'Kyoto last spring')
  assert.match(await page.getByLabel('Your favourite part—or what you’d change').inputValue(), /cooking class/)
  await shot('06-mobile-history-review')
  check('Reviewed day cards and reflections persist before confirmation')
  await page.getByLabel('Remember these interests for similar trips').check()
  await page.getByLabel('This was my own completed trip').check()
  await page.getByRole('button', { name: 'Save my chapter', exact: true }).click()
  await page.getByText(/Chapter saved. 100 points added/).waitFor()
  assert.equal((await api('/me/travel-style')).wallet.points, 100)
  await page.getByRole('button', { name: 'Little perks', exact: true }).click()
  await shot('07-mobile-perks')
  await page.getByRole('button', { name: 'Redeem 100 points · get 5 credits' }).click()
  await page.getByText('Five planning credits added. Your next idea is waiting.', { exact: true }).waitFor()
  assert.equal((await api('/me/travel-style')).wallet.credits, 8)
  check('A reviewed trip earns points that redeem into real planning credits')
  await page.getByRole('button', { name: 'Your style', exact: true }).click()
  await page.getByRole('heading', { name: 'Food & Culture', exact: true }).waitFor()
  await shot('08-mobile-travel-style')
  await page.setViewportSize({ width: 320, height: 740 })
  await shot('09-small-screen')
  check('Profile, history and perks remain usable at 390 and 320 pixels')
  assert.deepEqual(errors, [])
  await writeFile(`${out}/checks.json`, JSON.stringify({ checks, errors }, null, 2))
  console.log(JSON.stringify({ result: 'passed', checks: checks.length, screenshots: out }))
} catch (error) {
  await page.screenshot({ path: `${out}/failure.png`, fullPage: true }).catch(() => {})
  console.error(error); process.exitCode = 1
} finally {
  if (account) await page.request.delete(base + `/api/users/${account.user.id}`, { headers: { Authorization: `Bearer ${account.token}` } }).catch(() => {})
  await browser.close()
}
